// Builds js/levels.js: 10 hand-tuned tutorial levels + seeded generated levels for 6 worlds x 25.
// Run: node tools/build-levels.js && node tools/verify.js
const fs = require('fs'), path = require('path');
const E = require('../js/engine.js');
const { R } = require('./lib.js');
const SEED = 20261022;
const WORLDS = [
  { name: 'Sunny Start', icon: '🌤️' }, { name: 'Clever Canyon', icon: '🏜️' }, { name: 'Mirror Lake', icon: '🌊' },
  { name: 'Brainstorm Bay', icon: '⛈️' }, { name: 'Logic Peaks', icon: '🏔️' }, { name: 'Master Summit', icon: '👑' }];
const PER_WORLD = 25;
const TUTORIAL = [
  { t: 'm', eq: '6+4=4', tip: 'Tap a matchstick, then tap where it should go. Make the sum true!' },
  { t: 'b', g: ['S....', '###B#', '.....', 'E....'], tip: 'Swipe a crate (or tap it, then an arrow). Crates slide until they hit something.' },
  { t: 'r', g: ['>..c.', '.....', '...T.'], tip: 'Tap a mirror, then tap ⟳ to turn it. The ball bounces off mirrors.' },
  { t: 's', d: 1, g: ['.o.....', '.w.....', 'H..w..G', '#######'], tip: 'Tap ONE wooden plank to remove it. Get the explorer home safely.' },
  { t: 'm', eq: '3+3=5', tip: 'Sticks can move inside a digit too.' },
  { t: 'b', g: ['S..B.', '~~~~~', '....E'], tip: 'A crate that slides into water sinks and becomes a bridge.' },
  { t: 'r', g: ['>....', '.....', '.b..T'], tip: 'Mirrors without a pin can be dragged to any empty square.' },
  { t: 's', d: 1, g: ['...o...', '...w...', '.......', 'H.....G', '###^###'], tip: 'A falling boulder fills a spike pit.' },
  { t: 'm', eq: '2-7=3', tip: 'Signs are matchsticks too: + and − can change.' },
  { t: 's', d: 1, g: ['....o..', '....w..', '.o.....', '.w.....', 'H...M.G', '#######'], tip: 'Drop a boulder on the monster – but not in your own way!' }
];
function pickSpread(sorted, n) { const out = []; for (let i = 0; i < n; i++) out.push(sorted[Math.round(i * (sorted.length - 1) / (n - 1))]); return out; }
function main() {
  const rnd = R(SEED);
  const total = WORLDS.length * PER_WORLD, gen = total - TUTORIAL.length;
  const counts = { m: 0, b: 0, r: 0, s: 0 }; TUTORIAL.forEach(l => counts[l.t]++);
  const per = Math.ceil((total) / 4);
  const need = { m: per - counts.m, b: per - counts.b, r: per - counts.r, s: per - counts.s };
  // trim so needs add up to gen
  let sum = need.m + need.b + need.r + need.s; for (const k of ['m', 'b', 'r', 's']) if (sum > gen) { need[k]--; sum--; }
  const tutKeys = new Set(TUTORIAL.map(l => l.eq || l.g.join('/')));
  // matchsticks
  let ms = require('./gen-match.js').build(SEED).filter(l => !tutKeys.has(l.eq))
    .filter(l => !/(^|\D)0[+\-x]0|x0|0x|1x|x1(\D|$)/.test(l.answer) && !/^0/.test(l.answer));
  const seenAns = new Set(); ms.sort((a, b) => a.diff - b.diff); ms = ms.filter(l => (seenAns.has(l.answer) ? false : (seenAns.add(l.answer), true)));
  const pools = { m: pickSpread(ms, need.m) };
  const genT = { b: require('./gen-block.js'), r: require('./gen-ball.js'), s: require('./gen-rescue.js') };
  for (const t of ['b', 'r', 's']) {
    const perTier = Math.ceil(need[t] * 1.6 / 4);
    let all = genT[t].build(SEED + t.charCodeAt(0), perTier).filter(l => !tutKeys.has(l.g.join('/')));
    // prefer single-answer levels, then spread by difficulty
    all.sort((a, b) => a.diff - b.diff);
    pools[t] = pickSpread(all, need[t]);
  }
  for (const t in pools) pools[t].sort((a, b) => a.diff - b.diff);
  // interleave: each block of 4 holds one of each type in a seeded order
  const order = [];
  while (order.length < gen) {
    for (const t of rnd.shuffle(['m', 'b', 'r', 's'])) if (pools[t].length && order.length < gen) order.push(pools[t].shift());
  }
  const levels = TUTORIAL.concat(order).map((l, i) => {
    const o = { id: i + 1, t: l.t };
    if (l.t === 'm') o.eq = l.eq; else o.g = l.g;
    if (l.t === 's') o.d = l.d || 1;
    if (l.tip) o.tip = l.tip;
    return o;
  });
  const data = { worlds: WORLDS.map((w, i) => Object.assign({}, w, { from: i * PER_WORLD + 1, to: (i + 1) * PER_WORLD })), levels };
  const js = '/* ONE MOVE levels – generated by tools/build-levels.js (seed ' + SEED + '). Verified by tools/verify.js. */\n' +
    '(function(r,d){if(typeof module==="object"&&module.exports)module.exports=d;else r.OMLevels=d;})(this,' + JSON.stringify(data) + ');\n';
  fs.writeFileSync(path.join(__dirname, '../js/levels.js'), js);
  const c = { m: 0, b: 0, r: 0, s: 0 }; levels.forEach(l => c[l.t]++);
  console.log('levels', levels.length, JSON.stringify(c));
}
main();
